  // 而演示时没人会盯着引用胶囊逐个核对。
  function assertCites() {
    var ids = assets.map(function (a) { return a.id; });
    Object.keys(agentContexts).forEach(function (k) {
      agentContexts[k].questions.forEach(function (q) {
        q.cites.forEach(function (c) {
          if (ids.indexOf(c) < 0) {
            throw new Error("[DOMAIN_KB] 「 + q.id + 」 引用了不存在的资产：" + c);
          }
        });
      });
    });
  }

